import { useState } from 'react';
import { useQuery } from '@tanstack/react-query';
import { Search, FileAudio, Clock, MessageSquare } from 'lucide-react';
import { api } from '../services/api';

const SENTIMENT_BADGE = {
  positive: 'badge-emerald',
  negative: 'badge-red',
  neutral: 'badge-slate',
};

export default function CallHistoryPage() {
  const [search, setSearch] = useState('');
  const [selectedCall, setSelectedCall] = useState(null);

  const { data: calls = [], isLoading } = useQuery({
    queryKey: ['calls', search],
    queryFn: async () => {
      const params = new URLSearchParams();
      if (search) params.set('search', search);
      return (await api.get(`/calls?${params.toString()}`)).data.data;
    },
  });

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="section-title">Call History</h1>
          <p className="section-subtitle">Review call transcripts, AI summaries, sentiment, and follow-ups.</p>
        </div>
        <div className="relative w-full sm:w-72">
          <Search className="h-4 w-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
          <input
            className="input-field pl-9"
            placeholder="Search transcripts..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
          />
        </div>
      </div>

      <div className="grid lg:grid-cols-12 gap-6">
        <div className="lg:col-span-7 card divide-y divide-slate-100 overflow-hidden">
          {isLoading ? (
            <div className="p-12 text-center">
              <div className="inline-block h-8 w-8 border-2 border-indigo-200 border-t-indigo-600 rounded-full animate-spin" />
            </div>
          ) : calls.length === 0 ? (
            <div className="p-16 text-center">
              <div className="h-14 w-14 mx-auto rounded-2xl bg-slate-50 flex items-center justify-center mb-3">
                <FileAudio className="h-7 w-7 text-slate-300" />
              </div>
              <p className="text-sm text-slate-500">No call records yet.</p>
            </div>
          ) : (
            calls.map((c) => (
              <button
                key={c._id}
                onClick={() => setSelectedCall(c)}
                className={`w-full text-left p-4 hover:bg-slate-50/80 transition-colors ${
                  selectedCall?._id === c._id ? 'bg-indigo-50/40 border-l-2 border-l-indigo-600' : ''
                }`}
              >
                <div className="flex items-center justify-between">
                  <span className="font-medium text-sm text-slate-900">
                    {c.leadId?.name || c.customerPhone || 'Browser Voice Call'}
                  </span>
                  <div className="flex items-center gap-1.5 text-xs text-slate-500">
                    <Clock className="h-3 w-3" />
                    {c.durationSec}s
                  </div>
                </div>
                <p className="text-xs text-slate-500 mt-1 line-clamp-2 leading-relaxed">
                  {c.summary || 'Processing summary...'}
                </p>
                <div className="mt-2.5 flex items-center gap-2">
                  <span className="badge-slate text-[10px] capitalize">{c.status}</span>
                  <span className={`${SENTIMENT_BADGE[c.sentiment] || 'badge-slate'} text-[10px] capitalize`}>
                    {c.sentiment || 'unknown'}
                  </span>
                </div>
              </button>
            ))
          )}
        </div>

        <div className="lg:col-span-5 card p-6">
          {!selectedCall ? (
            <div className="text-center py-16">
              <div className="h-12 w-12 mx-auto rounded-2xl bg-slate-50 flex items-center justify-center mb-3">
                <MessageSquare className="h-6 w-6 text-slate-300" />
              </div>
              <p className="text-sm text-slate-400">Select a call to view its AI summary and transcript.</p>
            </div>
          ) : (
            <div className="space-y-5 animate-fade-in">
              <div>
                <h2 className="font-semibold text-slate-900 flex items-center gap-2">
                  AI Call Summary
                  <span className={`${SENTIMENT_BADGE[selectedCall.sentiment] || 'badge-slate'} text-[10px] capitalize`}>
                    {selectedCall.sentiment}
                  </span>
                </h2>
                <p className="text-sm text-slate-600 mt-2 leading-relaxed">
                  {selectedCall.summary || 'Summary is being generated by BullMQ worker.'}
                </p>
                {selectedCall.followUpRecommendation && (
                  <div className="mt-3 p-3 rounded-xl bg-indigo-50/50 border border-indigo-200/40">
                    <p className="text-xs font-semibold text-indigo-700">
                      ✨ Recommended: {selectedCall.followUpRecommendation}
                    </p>
                  </div>
                )}
              </div>
              <div className="border-t border-slate-100 pt-5">
                <h3 className="font-semibold text-sm text-slate-900 mb-3">Transcript</h3>
                <div className="space-y-2 max-h-80 overflow-y-auto">
                  {(selectedCall.transcript || []).map((t, idx) => (
                    <div
                      key={idx}
                      className={`text-xs p-3 rounded-xl ${
                        t.speaker === 'agent'
                          ? 'bg-indigo-50/50 border border-indigo-200/40'
                          : 'bg-slate-50 border border-slate-100'
                      }`}
                    >
                      <span className={`font-bold uppercase text-[10px] tracking-wider mr-1.5 ${
                        t.speaker === 'agent' ? 'text-indigo-600' : 'text-slate-500'
                      }`}>{t.speaker}:</span>
                      <span className="text-slate-700">{t.text}</span>
                    </div>
                  ))}
                  {(!selectedCall.transcript || selectedCall.transcript.length === 0) && (
                    <p className="text-xs text-slate-400 text-center py-4">No transcript available.</p>
                  )}
                </div>
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
